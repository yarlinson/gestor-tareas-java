-- Avisos generados por el proceso de recordatorios. Hay como máximo un aviso de cada tipo por
-- tarea: la restricción única hace que el proceso sea idempotente (no repite avisos).
CREATE TABLE notificaciones (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT       NOT NULL,
    tarea_id   BIGINT       NOT NULL,
    tipo       VARCHAR(20)  NOT NULL,
    mensaje    VARCHAR(300) NOT NULL,
    leida      BOOLEAN      NOT NULL DEFAULT FALSE,
    creada_en  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_notificaciones_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_notificaciones_tarea FOREIGN KEY (tarea_id) REFERENCES tareas (id) ON DELETE CASCADE,
    CONSTRAINT uk_notificaciones_tarea_tipo UNIQUE (tarea_id, tipo),
    CONSTRAINT ck_notificaciones_tipo CHECK (tipo IN ('POR_VENCER', 'VENCIDA'))
);

CREATE INDEX idx_notificaciones_usuario_leida ON notificaciones (usuario_id, leida);
