CREATE TABLE usuarios (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario VARCHAR(50)  NOT NULL,
    email          VARCHAR(120) NOT NULL,
    password       VARCHAR(100) NOT NULL,
    creado_en      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_usuarios_nombre_usuario UNIQUE (nombre_usuario),
    CONSTRAINT uk_usuarios_email UNIQUE (email)
);

CREATE TABLE tareas (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo         VARCHAR(150) NOT NULL,
    descripcion    VARCHAR(1000),
    completada     BOOLEAN      NOT NULL DEFAULT FALSE,
    fecha_limite   DATE,
    creada_en      TIMESTAMP WITH TIME ZONE NOT NULL,
    actualizada_en TIMESTAMP WITH TIME ZONE NOT NULL,
    usuario_id     BIGINT       NOT NULL,
    CONSTRAINT fk_tareas_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE
);

CREATE INDEX idx_tareas_usuario_completada ON tareas (usuario_id, completada);
