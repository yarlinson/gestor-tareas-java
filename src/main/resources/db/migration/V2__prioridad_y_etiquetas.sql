-- Prioridad de la tarea: 1 = BAJA, 2 = MEDIA, 3 = ALTA. Se guarda como número para poder
-- ordenar por importancia (con texto saldría ALTA, BAJA, MEDIA).
ALTER TABLE tareas ADD COLUMN prioridad INTEGER NOT NULL DEFAULT 2;
ALTER TABLE tareas ADD CONSTRAINT ck_tareas_prioridad CHECK (prioridad BETWEEN 1 AND 3);
CREATE INDEX idx_tareas_usuario_prioridad ON tareas (usuario_id, prioridad);

-- Etiquetas: pertenecen a un usuario y su nombre es único dentro de ese usuario.
CREATE TABLE etiquetas (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(30) NOT NULL,
    usuario_id BIGINT      NOT NULL,
    CONSTRAINT fk_etiquetas_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT uk_etiquetas_usuario_nombre UNIQUE (usuario_id, nombre)
);

-- Relación muchos a muchos entre tareas y etiquetas.
CREATE TABLE tarea_etiqueta (
    tarea_id    BIGINT NOT NULL,
    etiqueta_id BIGINT NOT NULL,
    PRIMARY KEY (tarea_id, etiqueta_id),
    CONSTRAINT fk_tarea_etiqueta_tarea FOREIGN KEY (tarea_id) REFERENCES tareas (id) ON DELETE CASCADE,
    CONSTRAINT fk_tarea_etiqueta_etiqueta FOREIGN KEY (etiqueta_id) REFERENCES etiquetas (id) ON DELETE CASCADE
);
CREATE INDEX idx_tarea_etiqueta_etiqueta ON tarea_etiqueta (etiqueta_id);
